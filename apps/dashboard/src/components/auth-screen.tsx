import { FingerprintIcon } from "@phosphor-icons/react/dist/csr/Fingerprint";
import { Link } from "@tanstack/react-router";
import { type FormEvent, useEffect, useState } from "react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { addPasskey, api, signIn } from "@/lib/auth";

export function AuthScreen({ mode }: { mode: "login" | "setup" | "recover" }) {
  const [code, setCode] = useState("");
  const [name, setName] = useState("");
  const [keyName, setKeyName] = useState("My passkey");
  const [enrolling, setEnrolling] = useState(false);
  const [ready, setReady] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  useEffect(() => {
    let active = true;
    api<{ configured: boolean; enrolling: boolean }>("/setup/status")
      .then((status) => {
        if (!active) return;
        if (mode === "login" && !status.configured) {
          location.replace("/setup");
          return;
        }
        if (mode === "setup" && status.configured && !status.enrolling) {
          location.replace("/login");
          return;
        }
        setEnrolling(mode !== "login" && status.enrolling);
        setReady(true);
      })
      .catch((e: Error) => {
        if (active) setError(e.message);
      });
    return () => {
      active = false;
    };
  }, [mode]);

  async function submit(event: FormEvent) {
    event.preventDefault();
    setBusy(true);
    setError("");
    try {
      if (!window.isSecureContext || !window.PublicKeyCredential)
        throw new Error(
          "Passkeys require HTTPS and a browser with WebAuthn support. Local development can use localhost.",
        );
      if (mode === "login") {
        await signIn();
        location.assign("/");
      } else if (enrolling) {
        await addPasskey(keyName.trim(), true);
        location.assign("/security");
      } else {
        await api(`/${mode === "setup" ? "setup" : "recovery"}/start`, {
          code,
          name: name || "Owner",
        });
        setCode("");
        setEnrolling(true);
      }
    } catch (e) {
      setError(e instanceof Error ? e.message : "Please try again.");
    } finally {
      setBusy(false);
    }
  }
  const title =
    mode === "login"
      ? "Welcome back"
      : mode === "setup"
        ? "Set up your workspace"
        : "Recover your account";
  return (
    <main
      id="main"
      className="flex min-h-svh items-center justify-center bg-muted/30 px-6 py-12"
    >
      <div className="w-full max-w-sm space-y-8">
        <div className="space-y-3">
          <span className="text-xl font-semibold tracking-tight">tenet</span>
          <h1 className="text-2xl font-semibold tracking-tight">{title}</h1>
          <p className="text-sm leading-6 text-muted-foreground">
            {mode === "login"
              ? "Use a passkey to access your infrastructure."
              : enrolling
                ? "Create a passkey using your device or security key. Your device will ask you to verify your identity."
                : mode === "setup"
                  ? "Enter the one-use setup code generated by your deployment administrator."
                  : "Enter a saved recovery code. This immediately signs out all sessions and revokes all existing passkeys. You’ll then register a replacement."}
          </p>
        </div>
        <form onSubmit={submit} className="space-y-5">
          {mode !== "login" && !enrolling && (
            <>
              {mode === "setup" && (
                <div className="space-y-2">
                  <label htmlFor="owner-name" className="text-sm font-medium">
                    Your name
                  </label>
                  <Input
                    id="owner-name"
                    autoComplete="name"
                    maxLength={80}
                    required
                    value={name}
                    onChange={(e) => setName(e.target.value)}
                  />
                </div>
              )}
              <div className="space-y-2">
                <label htmlFor="code" className="text-sm font-medium">
                  {mode === "setup" ? "Setup code" : "Recovery code"}
                </label>
                <Input
                  id="code"
                  type="password"
                  autoComplete="off"
                  spellCheck={false}
                  maxLength={128}
                  required
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                />
              </div>
            </>
          )}
          {enrolling && (
            <div className="space-y-2">
              <label htmlFor="key-name" className="text-sm font-medium">
                Passkey name
              </label>
              <Input
                id="key-name"
                maxLength={80}
                required
                value={keyName}
                onChange={(e) => setKeyName(e.target.value)}
              />
            </div>
          )}
          {error && (
            <p role="alert" className="text-sm text-destructive">
              {error}
            </p>
          )}
          <Button type="submit" className="w-full" disabled={!ready || busy}>
            <FingerprintIcon aria-hidden="true" />
            {busy
              ? "Please wait…"
              : mode === "login"
                ? "Sign in with a passkey"
                : enrolling
                  ? "Create passkey"
                  : "Continue"}
          </Button>
        </form>
        <div className="text-center text-sm text-muted-foreground">
          {mode === "login" ? (
            <Link className="underline underline-offset-4" to="/recover">
              Lost access to your passkeys?
            </Link>
          ) : (
            <Link className="underline underline-offset-4" to="/login">
              Back to sign in
            </Link>
          )}
        </div>
      </div>
    </main>
  );
}
